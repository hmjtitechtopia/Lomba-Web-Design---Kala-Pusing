const rawSlug = new URLSearchParams(window.location.search)
  .get("tradisi")
  ?.trim()
  .toLowerCase();
const slug = rawSlug || "siat-tipat-bantal";
const tradition = Object.hasOwn(traditions, slug) ? traditions[slug] : null;

if (!tradition) {
  window.location.replace("daftar-tradisi.html?wilayah=badung");
} else {
  const setText = (key, value) => {
    document.querySelector(`[data-detail-${key}]`).textContent = value;
  };

  document.title = `${tradition.name} - Sekala`;
  document.querySelector('meta[name="description"]').content =
    tradition.description ||
    `Kenali tradisi ${tradition.name} dari Badung, Bali.`;
  setText("breadcrumb", `Tradisi ${tradition.name}`);
  setText("title", tradition.title);
  setText("intro", tradition.intro);
  setText("history-heading", tradition.historyHeading);
  setText("history", tradition.history);
  setText("extra-heading", tradition.extraHeading);
  setText("extra", tradition.extra);
  setText("purpose", tradition.purpose);
  setText("preservation", tradition.preservation);

  const image = document.querySelector("[data-detail-image]");
  image.src = `../img/${tradition.image}`;
  image.alt = tradition.imageAlt;
  [image.width, image.height] = tradition.imageSize;

  const fillList = (key, items, makeItem) => {
    const list = document.querySelector(`[data-detail-${key}]`);
    list.replaceChildren(...items.map(makeItem));
  };

  fillList("values", tradition.values, (value) => {
    const item = document.createElement("li");
    item.textContent = value;
    return item;
  });
  fillList("steps", tradition.steps, (step) => {
    const item = document.createElement("li");
    item.textContent = step;
    return item;
  });
  fillList("sources", tradition.sources, ([label, url]) => {
    const item = document.createElement("li");
    const link = document.createElement("a");
    link.href = url;
    link.target = "_blank";
    link.rel = "noopener noreferrer";
    link.textContent = label;
    item.append(link);
    return item;
  });

  const gallery = document.querySelector("[data-detail-gallery]");
  const galleryGrid = document.querySelector("[data-detail-gallery-grid]");
  if (tradition.gallery?.length) {
    galleryGrid.replaceChildren(
      ...tradition.gallery.map((item) => {
        const photo = document.createElement("img");
        photo.src = `../img/${item.src}`;
        photo.alt = item.alt;
        photo.width = item.width;
        photo.height = item.height;
        photo.loading = "lazy";
        return photo;
      }),
    );
    gallery.hidden = false;
  } else {
    galleryGrid.replaceChildren();
    gallery.hidden = true;
  }

  document.querySelector("[data-detail-fallback]").hidden = true;
  document.querySelector("[data-detail-view]").hidden = false;
}
